import struct, math
from typing import Tuple, List

# -------------------------------
# Utilidades BMP (24 bpp, BI_RGB)
# -------------------------------
def leer_bmp(path: str) -> Tuple[bytearray, bytearray, int, int, int, int]:
    """
    Lee un BMP y retorna:
      header (bytes antes de los datos de píxel),
      pixels (datos de píxel),
      width, height (int),
      bpp (bits por pixel),
      row_size (bytes por fila, con padding a múltiplos de 4)

    Valida 'BM', 24 bpp y sin compresión (BI_RGB).
    """
    with open(path, 'rb') as f:
        data = bytearray(f.read())

    # Firma 'BM'
    if data[0:2] != b'BM':
        raise ValueError("No es un archivo BMP válido (falta firma 'BM').")

    # Encabezados BMP/DIB
    pixel_offset = struct.unpack_from('<I', data, 10)[0]
    width = struct.unpack_from('<i', data, 18)[0]
    height = struct.unpack_from('<i', data, 22)[0]
    bpp = struct.unpack_from('<H', data, 28)[0]
    compression = struct.unpack_from('<I', data, 30)[0]

    if bpp != 24:
        raise ValueError(f"Se requiere BMP de 24 bpp (RGB). Este es {bpp} bpp.")
    if compression != 0:
        raise ValueError("Se requiere BMP sin compresión (BI_RGB).")

    # Tamaño de fila con padding a múltiplos de 4
    row_size = ((abs(width) * 3 + 3) // 4) * 4

    header = data[:pixel_offset]
    pixels = data[pixel_offset:]

    # Comprobación de tamaño esperado de datos
    expected_pixels = row_size * abs(height)
    if len(pixels) < expected_pixels:
        raise ValueError("El archivo BMP parece truncado o corrupto (pixeles insuficientes).")

    return header, pixels, width, height, bpp, row_size


def guardar_bmp(path: str, header: bytearray, pixels: bytearray):
    with open(path, 'wb') as f:
        f.write(header)
        f.write(pixels)


def indices_carrier(width: int, height: int, row_size: int) -> List[int]:
    """
    Retorna los índices (relativos a 'pixels') que corresponden a bytes de color B,G,R
    (excluye los bytes de padding por fila).
    """
    h = abs(height)
    carriers = []
    row_payload = width * 3  # bytes B,G,R por fila
    base = 0
    for _ in range(h):
        carriers.extend(range(base, base + row_payload))
        base += row_size
    return carriers


def capacidad_bytes(width: int, height: int) -> int:
    """Capacidad teórica con 1 LSB por canal B,G,R (≈ (W*H*3)/8 bytes)."""
    return (abs(width) * abs(height) * 3) // 8


# -------------------------------
# Conversión bits <-> bytes (MSB)
# -------------------------------
def _to_bits_be(data: bytes) -> list:
    """Convierte bytes a bits (MSB→LSB por byte)."""
    bits = []
    for byte in data:
        for i in range(7, -1, -1):
            bits.append((byte >> i) & 1)
    return bits

def _bits_to_bytes_be(bits: list) -> bytes:
    """Convierte lista de bits (MSB→LSB por byte) a bytes."""
    out = bytearray()
    for i in range(0, len(bits), 8):
        byte = 0
        for b in bits[i:i+8]:
            byte = (byte << 1) | b
        out.append(byte)
    return bytes(out)

def embed_lsb(src_path: str, dst_path: str, mensaje: str):
    """
    Incrusta: [32 bits longitud (LE)][mensaje UTF-8] en los LSB de bytes B,G,R
    recorriendo portadores en orden secuencial (excluye padding).
    """
    header, pixels, w, h, bpp, row_size = leer_bmp(src_path)
    carriers = indices_carrier(w, h, row_size)

    msg_bytes = mensaje.encode('utf-8')
    # 4 bytes de longitud (little-endian) + mensaje
    datos = struct.pack('<I', len(msg_bytes)) + msg_bytes
    bits = _to_bits_be(datos)

    if len(bits) > len(carriers):
        raise ValueError(f"Mensaje demasiado grande. Bits necesarios={len(bits)}, capacidad bits={len(carriers)}")

    pixels_mod = bytearray(pixels)
    for i, bit in enumerate(bits):
        pos = carriers[i]
        pixels_mod[pos] = (pixels_mod[pos] & 0xFE) | bit

    guardar_bmp(dst_path, header, pixels_mod)
    print(f"[OK] Incrustados {len(msg_bytes)} bytes en '{dst_path}' usando LSB secuencial.")


def extract_lsb(stego_path: str) -> str:
    """
    Extrae un mensaje embebido con 'embed_lsb'.
    **Corregido**: reconstruye 4 bytes de longitud desde 32 bits (MSB→LSB por byte) y los interpreta en LE.
    """
    header, pixels, w, h, bpp, row_size = leer_bmp(stego_path)
    carriers = indices_carrier(w, h, row_size)

    # 1) Leer los primeros 32 bits y convertirlos a 4 bytes (MSB→LSB por byte),
    #    luego interpretar esos bytes como little-endian ('<I').
    len_bits = [(pixels[carriers[i]] & 1) for i in range(32)]
    len_bytes = _bits_to_bytes_be(len_bits)
    msg_len = struct.unpack('<I', len_bytes)[0]

    # 2) Leer a continuación msg_len * 8 bits de mensaje
    total_bits = 32 + msg_len * 8
    if total_bits > len(carriers):
        raise ValueError("La longitud indicada excede la capacidad (archivo dañado o formato incorrecto).")

    msg_bits = [(pixels[carriers[i]] & 1) for i in range(32, total_bits)]
    out = _bits_to_bytes_be(msg_bits)
    return out.decode('utf-8')


# ----------------
# Métrica de PSNR
# ----------------
def calcular_psnr(original_path: str, stego_path: str) -> float:
    """
    PSNR calculado sobre bytes B,G,R (excluye padding).
    """
    _, pix_o, w, h, bpp, row_size = leer_bmp(original_path)
    _, pix_s, *_ = leer_bmp(stego_path)

    carriers = indices_carrier(w, h, row_size)
    mse = 0.0
    for idx in carriers:
        diff = int(pix_o[idx]) - int(pix_s[idx])
        mse += diff * diff
    mse /= len(carriers)

    if mse == 0:
        print("MSE=0 → PSNR=∞ (no hay diferencias).")
        return float('inf')

    psnr = 10.0 * math.log10((255 ** 2) / mse)
    print(f"MSE: {mse:.6f}")
    print(f"PSNR: {psnr:.2f} dB (≈ >40 dB suele ser imperceptible)")
    return psnr


