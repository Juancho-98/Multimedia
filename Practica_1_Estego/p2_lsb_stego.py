"""# Generador de portadas y pruebas de capacidad"""

import math

def capacidad_max_bytes(width: int, height: int) -> int:
    cap_bits = abs(width) * abs(height) * 3
    cap_bits_utiles = cap_bits - 32  # restar 32 bits de la longitud
    if cap_bits_utiles < 0:
        return 0
    return cap_bits_utiles // 8

def ejecutar_prueba_capacidad(img_path: str, tamanos: list, umbral_psnr_db: float = 40.0):
    """
    Para cada tamaño de mensaje:
      - Inserta con embed_lsb()
      - Extrae y verifica
      - Calcula PSNR
      - Imprime fila con: (W×H), tamaño msg, PSNR, Imperceptible? (Sí/No)

    Requiere:
      - leer_bmp, indices_carrier, embed_lsb, extract_lsb, calcular_psnr
    """
    header, pixels, w, h, bpp, row_size = leer_bmp(img_path)
    cap_aprox = (abs(w)*abs(h)*3) // 8  # aprox, sin restar los 4 bytes
    cap_max = capacidad_max_bytes(w, h)  # exacto, descontando 4 bytes (32 bits)

    print(f"Imagen: {w}×{h} px | Capacidad máx. (bytes, con 1 LSB/canal) = {cap_max} (aprox: {cap_aprox})")
    print(f"{'Tamaño mensaje (bytes)':>22}  {'PSNR (dB)':>10}  {'¿Imperceptible?':>16}")

    resultados = []
    for n in tamanos:
        etiqueta = f"stego_{abs(w)}x{abs(h)}_{n}.bmp"
        try:
            msg = 'A' * n
            embed_lsb(img_path, etiqueta, msg)
            rec = extract_lsb(etiqueta)
            assert rec == msg, "¡Error: extracción no coincide!"

            psnr = calcular_psnr(img_path, etiqueta)
            imperc = "Sí" if (psnr == float('inf') or psnr >= umbral_psnr_db) else "No"
            print(f"{n:>22}  {psnr:>10.2f}  {imperc:>16}")
            resultados.append((f"{abs(w)}×{abs(h)}", n, psnr, imperc))
        except Exception as e:
            print(f"{n:>22}  {'—':>10}  {'ERROR':>16}  -> {e}")
            resultados.append((f"{abs(w)}×{abs(h)}", n, None, f"ERROR: {e}"))

    return resultados, cap_max

def prueba_capacidad_max(img_path: str, umbral_psnr_db: float = 40.0):
    """
    Inserta un mensaje del tamaño máximo y mide PSNR.
    """
    header, pixels, w, h, bpp, row_size = leer_bmp(img_path)
    cap_max = capacidad_max_bytes(w, h)
    etiqueta = f"stego_{abs(w)}x{abs(h)}_capMax.bmp"

    print(f"Imagen: {w}×{h} px | Capacidad máxima exacta (bytes) = {cap_max}")
    try:
        msg = 'A' * cap_max
        embed_lsb(img_path, etiqueta, msg)
        rec = extract_lsb(etiqueta)
        assert rec == msg, "¡Error: extracción no coincide!"
        psnr = calcular_psnr(img_path, etiqueta)
        imperc = "Sí" if (psnr == float('inf') or psnr >= umbral_psnr_db) else "No"
        print(f"{'Capacidad máx.':>22}  {psnr:>10.2f}  {imperc:>16}")
        return (f"{abs(w)}×{abs(h)}", cap_max, psnr, imperc)
    except Exception as e:
        print(f"{'Capacidad máx.':>22}  {'—':>10}  {'ERROR':>16}  -> {e}")
        return (f"{abs(w)}×{abs(h)}", cap_max, None, f"ERROR: {e}")

