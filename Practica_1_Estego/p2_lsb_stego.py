def generar_bmp_sintetica(path='imagen.bmp', w=512, h=512):
    import numpy as np
    from PIL import Image
    arr = np.zeros((h, w, 3), dtype=np.uint8)
    for y in range(h):
        for x in range(w):
            arr[y, x] = (x % 256, y % 256, (x+y) % 256)  # gradiente simple
    Image.fromarray(arr, 'RGB').save(path, format='BMP')
    print(f"Generada '{path}' {w}x{h} (24 bpp).")

