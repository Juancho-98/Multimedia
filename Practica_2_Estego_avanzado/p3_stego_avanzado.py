import numpy as np
import matplotlib.pyplot as plt

def mostrar_histograma_bgr(original_path: str, stego_path: str):
    _, p0, w, h, bpp, row_size = leer_bmp(original_path)
    _, p1, *_ = leer_bmp(stego_path)
    carriers = indices_carrier(w, h, row_size)

    b0 = np.array([p0[i] for i in carriers[0::3]])
    g0 = np.array([p0[i] for i in carriers[1::3]])
    r0 = np.array([p0[i] for i in carriers[2::3]])

    b1 = np.array([p1[i] for i in carriers[0::3]])
    g1 = np.array([p1[i] for i in carriers[1::3]])
    r1 = np.array([p1[i] for i in carriers[2::3]])

    fig, axs = plt.subplots(3, 2, figsize=(10, 8))
    canales = [('B', b0, b1), ('G', g0, g1), ('R', r0, r1)]

    for row, (name, o, s) in enumerate(canales):
        axs[row, 0].hist(o, bins=256, range=(0,255), color=name.lower())
        axs[row, 0].set_title(f'Original {name}')
        axs[row, 1].hist(s, bins=256, range=(0,255), color=name.lower())
        axs[row, 1].set_title(f'Stego {name}')

    plt.tight_layout()
    plt.show()

mostrar_histograma_bgr('/content/Images/volcan.bmp', '/content/Images/stego_seguroVolcan.bmp')