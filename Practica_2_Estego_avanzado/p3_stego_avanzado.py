def convertir_a_bmp_24bpp(entrada_path: str, salida_path: str = 'imagen.bmp'):
    """
    Convierte una imagen (PNG/JPG/etc.) a BMP 24 bpp sin compresión.
    """
    try:
        from PIL import Image
        img = Image.open(entrada_path).convert('RGB')
        img.save(salida_path, format='BMP')
        print(f"Convertido '{entrada_path}' → '{salida_path}' (24 bpp).")
    except Exception as e:
        raise RuntimeError(f"No se pudo convertir '{entrada_path}' a BMP 24 bpp: {e}")



