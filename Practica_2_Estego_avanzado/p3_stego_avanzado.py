# PRACTICA 2 — Esteganografía en BMP 24 bpp
# - Carriers SIN padding (B, G, R)
# - PRNG determinista derivado de contraseña (permutación)
# - Cifrado XOR con clave de SHA-256 (modo contador, docente)
